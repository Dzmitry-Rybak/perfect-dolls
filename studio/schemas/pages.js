/**
 * Страницы разделов — Squids, Dolls, Portraits.
 *
 * На каждой показываются четыре работы из архива. Здесь выбирается,
 * какие именно: перетащите нужные, лишние удалите. Больше четырёх
 * не поместится — пятую админка не даст добавить.
 *
 * Страница показывает ровно выбранные — две так две, недостающие не
 * добираются. Если не выбрано ничего, возьмёт первые четыре работы
 * раздела по полю «Порядок в галерее», чтобы раздел не был пустым.
 * Выбранная работа, если её удалить из архива, просто исчезнет
 * со страницы, а не оставит дыру.
 */
const picks = (name, title, kind) => ({
  name,
  title,
  type: 'array',
  /* Сюда не добавляют новую работу, а выбирают из уже заведённых в
     «Работах». Без этой подсказки «Add item» читался как «добавить
     куклу», и человек ждал полей для снимков, а получал список. */
  description: 'Выбор из «Работ»: новую работу сначала заведите там, '
    + 'со снимками, — потом она появится в этом списке. Не больше четырёх. '
    + 'Порядок слева направо — как здесь.',
  of: [
    {
      type: 'reference',
      to: [{ type: 'work' }],
      options: {
        /* Уже выбранные из списка убираем. Раньше их можно было выбрать
           второй раз — и сразу получить ошибку про повтор. */
        filter: ({ parent }) => ({
          filter: 'kind == $kind && !(_id in $taken)',
          params: {
            kind,
            taken: (parent ?? []).map((r) => r?._ref).filter(Boolean),
          },
        }),
        disableNew: true,
      },
    },
  ],
  validation: (R) => R.max(4).unique(),
});

export default {
  name: 'pages',
  title: 'Страницы разделов',
  type: 'document',
  fields: [
    picks('squidPicks',    'Squids — четыре работы',    'squid'),
    picks('dollPicks',     'Dolls — четыре работы',     'doll'),
    picks('portraitPicks', 'Portraits — четыре работы', 'portrait'),
  ],
  preview: {
    prepare: () => ({ title: 'Страницы разделов' }),
  },
};
