/** Звёздочка в один росчерк: пять лучей через один, как её и рисуют. */
function star(cx, cy, r, turn) {
  const pt = (i) => {
    const a = turn + (i * 2 * Math.PI) / 5 - Math.PI / 2;
    return `${(cx + Math.cos(a) * r).toFixed(1)},${(cy + Math.sin(a) * r).toFixed(1)}`;
  };
  return `M${pt(0)}L${pt(2)}L${pt(4)}L${pt(1)}L${pt(3)}Z`;
}

export default function SheetDoodles({ side = 'left', className = '' }) {
  const ref = useRef(null);
  const [box, setBox] = useState(null);

  /* Рисуем в настоящих пикселях поля, поэтому его размер нужен заранее. */
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return undefined;
    const ro = new ResizeObserver(([e]) => {
      const { width, height } = e.contentRect;
      setBox(width > 0 ? { w: width, h: height } : null);
    });
    ro.observe(el);
    return () => ro.disconnect();
  }, []);

  const s = SIDES[side];
  let body = null;
  if (box) {
    const kx = box.w / (s.to - s.from);
    const ky = box.h / (BOTTOM - TOP);
    const X = (x) => (x - s.from) * kx;
    const Y = (y) => (y - TOP) * ky;
    const map = (d) => d.replace(/(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g,
      (_, x, y) => `${X(+x).toFixed(1)},${Y(+y).toFixed(1)}`);
    /* Размер звёзд — от высоты листа: высота у нас и у Риты близка
       по пропорциям, а ширина поля сжата. */
    const k = ky * 0.85;

    body = (
      <>
        <g fill="none" stroke={INK} strokeWidth="2.4" strokeLinecap="round" strokeDasharray="13 9">
          {s.lines.map((d, i) => <path key={i} d={map(d)} />)}
        </g>
        <g fill="none" stroke={INK} strokeWidth="1.9" strokeLinejoin="round" strokeLinecap="round">
          {s.stars.map(([x, y, r, turn], i) => (
            <path key={i} d={star(X(x), Y(y), r * k, turn)} />
          ))}
        </g>
        <g fill={INK}>
          {s.dots.map(([x, y], i) => (
            <circle key={i} cx={X(x).toFixed(1)} cy={Y(y).toFixed(1)} r="3.2" />
          ))}
        </g>
      </>
    );
  }

  return (
    <svg
      ref={ref}
      className={`${styles.doodles} ${className}`}
      width="100%"
      height="100%"
      aria-hidden="true"
      focusable="false"
    >
      {body}
    </svg>
  );
}
