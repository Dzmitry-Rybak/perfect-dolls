import styles from './SheetDoodles.module.css';

/**
 * Рисунок на полях тетрадного листа в конструкторе.
 *
 * СНЯТ С РЕФЕРЕНСА РИТЫ, А НЕ ПРИДУМАН. Те же линии на тех же местах:
 * слева — волна под запиской, уходящая вверх, и длинная линия с петлёй,
 * которая спускается к низу листа; справа — линия сверху с петлёй,
 * уходящая вправо, и арка внизу. Звёзды и точки стоят там же, где у неё.
 * Только линии ровные: у Риты они от руки, здесь — плавные кривые.
 *
 * Петлю слева нарисовал шире, чем у неё: левое поле у нас сжато
 * сильнее правого, и круглая петля превращалась в узкий овал.
 *
 * Координаты ниже — в пикселях её скетча (лист там примерно
 * 60…1390 × 30…1200). Каждое поле растягивается на своё место на
 * нашем листе. Растяжение у кривой Безье — тоже кривая Безье, так что
 * линия остаётся гладкой. А вот звёзды и точки не растягиваем:
 * переносим только их центры, размер у них свой, иначе звезда на
 * узком поле сплющилась бы.
 *
 * Это украшение: событий не ловит, для скринридера скрыто, и на
 * узком экране его нет — там лист по ширине сквида, полей не остаётся.
 */

